#!/usr/bin/env node
/**
 * One-time personal production pairing helper.
 *
 * 1. Generates a device token + SHA-256 digest
 * 2. Prints Vercel env vars to set
 * 3. Optionally writes ../Config/Local.xcconfig so the iPhone app auto-pairs
 *
 * Usage:
 *   node scripts/setup-personal.mjs
 *   node scripts/setup-personal.mjs --url https://tracal-xxx.vercel.app --write-xcconfig
 */
import { createHash, randomBytes } from "node:crypto";
import { writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, "../..");
const xcconfigPath = join(repoRoot, "Config/Local.xcconfig");

const args = parseArgs(process.argv.slice(2));
const rawToken = randomBytes(32).toString("base64url");
const digest = createHash("sha256").update(rawToken, "utf8").digest("hex");
const baseURL = (args.url || "").replace(/\/$/, "");

console.log(`
Tracal personal gateway setup
=============================

1) Deploy this folder to Vercel (from vertex-meal-gateway/):

   npx vercel

2) Set these Vercel environment variables (Production):

   TRACAL_DEVICE_TOKEN_SHA256=${digest}
   TRACAL_GEMINI_API_KEY=<your Gemini API key from Google AI Studio>
   # optional:
   # TRACAL_MODEL=gemini-3-flash-preview

3) Redeploy after env vars are set.

4) On the phone: if Local.xcconfig is filled and the app is rebuilt, pairing
   is automatic. Otherwise Settings → Connect gateway still works.
`);

if (args.writeXcconfig) {
  if (!baseURL) {
    console.error("\n--write-xcconfig requires --url https://your-app.vercel.app\n");
    process.exit(1);
  }
  if (existsSync(xcconfigPath) && !args.force) {
    console.error(
      `\nRefusing to overwrite existing ${xcconfigPath}.\nPass --force to replace it.\n`,
    );
    process.exit(1);
  }
  // xcconfig treats // as a comment, so rewrite https://host → https:/$()/host
  const xcURL = baseURL
    .replace(/^https:\/\//, "https:/$()/")
    .replace(/^http:\/\//, "http:/$()/");
  const contents = `// Generated by vertex-meal-gateway/scripts/setup-personal.mjs
// gitignored — do not commit.
// URL form uses https:/$()/… so // is not treated as an xcconfig comment.

TRACAL_GATEWAY_BASE_URL = ${xcURL}
TRACAL_GATEWAY_DEVICE_TOKEN = ${rawToken}
`;
  writeFileSync(xcconfigPath, contents, { mode: 0o600 });
  console.log(`Wrote ${xcconfigPath}`);
  console.log("Run: xcodegen generate   (if you use XcodeGen)");
  console.log("Then rebuild Tracal on your iPhone.\n");
} else {
  console.log(`Raw device token (phone / Local.xcconfig only — not Vercel):\n${rawToken}\n`);
  console.log(`Optional: write Local.xcconfig after you know the Vercel URL:

  node scripts/setup-personal.mjs --url https://YOUR.vercel.app --write-xcconfig
`);
  console.log(
    "If you re-run later without saving the raw token above, generate a new pair.\n",
  );
}

function parseArgs(argv) {
  const out = { writeXcconfig: false, force: false, url: "" };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--write-xcconfig") out.writeXcconfig = true;
    else if (arg === "--force") out.force = true;
    else if (arg === "--url") out.url = argv[++i] || "";
    else if (arg.startsWith("--url=")) out.url = arg.slice("--url=".length);
  }
  return out;
}
